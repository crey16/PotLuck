create table public.modules (
  id           bigint generated by default as identity primary key,
  title        text not null,
  description  text not null default '',
  order_index  integer not null,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);

create type public.lesson_type as enum ('concept', 'quiz', 'drill', 'micro_hand');

-- content_json shape:
-- {
--   "screens": [
--     { "type": "info" | "question" | "drill",
--       "content": "markdown",
--       "choices": [{"id":"a","label":"Fold"}],
--       "correct_choice_id": "b" }
--   ],
--   "skill_tags": ["pot_odds", "position"],
--   "xp_reward": 10
-- }
create table public.lessons (
  id                     bigint generated by default as identity primary key,
  module_id              bigint not null references public.modules(id) on delete cascade,
  lesson_type            public.lesson_type not null,
  title                  text not null,
  order_index            integer not null,
  content_json           jsonb not null,
  estimated_time_seconds integer default 300,
  difficulty             integer default 1,
  version                integer not null default 1,
  is_active              boolean not null default true,
  created_at             timestamptz not null default now()
);
create index lessons_module_idx on public.lessons (module_id, order_index);

create table public.scenarios (
  id            bigint generated by default as identity primary key,
  module_id     bigint not null references public.modules(id) on delete cascade,
  skill_tag     text not null,
  difficulty    integer not null,
  scenario_json jsonb not null,
  version       integer not null default 1,
  is_active     boolean not null default true,
  created_at    timestamptz not null default now()
);
create index scenarios_skill_idx on public.scenarios (skill_tag, difficulty);

-- A deterministic, one-decision poker spot.
-- situation_json: { blinds, effective_stack_bb, hero{seat,position,cards},
--                   villains[], pre_action[], pot_bb, board[] }
-- choices_json:   [{ id, label, action, amount_bb }]
create table public.table_scenarios (
  id                     bigint generated by default as identity primary key,
  module_id              bigint not null references public.modules(id) on delete cascade,
  difficulty             integer not null,
  skill_tag              text not null,
  street                 text not null,
  prompt_title           text not null,
  situation_json         jsonb not null,
  choices_json           jsonb not null,
  correct_choice_id      text not null,
  acceptable_choice_ids  jsonb,
  explanation            text not null,
  rule_of_thumb          text not null,
  is_active              boolean not null default true,
  created_at             timestamptz not null default now()
);
create index table_scenarios_skill_idx on public.table_scenarios (skill_tag, difficulty, street);

