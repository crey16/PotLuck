create table public.friend_requests (
  id           bigint generated by default as identity primary key,
  from_user_id uuid not null references public.profiles(id) on delete cascade,
  to_user_id   uuid not null references public.profiles(id) on delete cascade,
  status       text not null default 'pending',   -- pending | accepted | declined
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (from_user_id, to_user_id),
  check (from_user_id <> to_user_id)
);
create index friend_requests_to_idx on public.friend_requests (to_user_id, status);

-- Stored bidirectionally (two rows per friendship), matching StackSchool.
create table public.friends (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references public.profiles(id) on delete cascade,
  friend_user_id uuid not null references public.profiles(id) on delete cascade,
  created_at     timestamptz not null default now(),
  unique (user_id, friend_user_id),
  check (user_id <> friend_user_id)
);

-- ---------------------------------------------------------------------
-- NEW: head-to-head challenges
--
-- A challenge is a fixed set of hands both players answer, so scores are
-- comparable. Hands are frozen at creation time into challenge_hands.
-- ---------------------------------------------------------------------
create table public.challenges (
  id            uuid primary key default gen_random_uuid(),
  creator_id    uuid not null references public.profiles(id) on delete cascade,
  opponent_id   uuid references public.profiles(id) on delete cascade,  -- null = open challenge
  drill_kind    text not null,             -- which drill this tests
  hand_count    integer not null default 10,
  status        text not null default 'pending',  -- pending | active | complete | expired
  expires_at    timestamptz not null default (now() + interval '7 days'),
  created_at    timestamptz not null default now()
);
create index challenges_opponent_idx on public.challenges (opponent_id, status);
create index challenges_creator_idx on public.challenges (creator_id, status);

create table public.challenge_hands (
  id           bigint generated by default as identity primary key,
  challenge_id uuid not null references public.challenges(id) on delete cascade,
  order_index  integer not null,
  payload      jsonb not null,   -- the frozen generated spot
  answer       jsonb not null,   -- correct answer + explanation data
  unique (challenge_id, order_index)
);

create table public.challenge_results (
  id             bigint generated by default as identity primary key,
  challenge_id   uuid not null references public.challenges(id) on delete cascade,
  user_id        uuid not null references public.profiles(id) on delete cascade,
  correct_count  integer not null default 0,
  total_count    integer not null default 0,
  elapsed_ms     integer,
  answers        jsonb,
  completed_at   timestamptz not null default now(),
  unique (challenge_id, user_id)
);

