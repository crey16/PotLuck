-- =====================================================================
-- HCWK Wizard — initial schema
--
-- Ported from StackSchool (FastAPI/SQLAlchemy, 15 tables) with three changes:
--   1. users.id becomes uuid and references auth.users — Supabase Auth owns
--      identity now, so hashed_password / refresh_tokens / password_reset_tokens
--      are gone (Supabase handles all three).
--   2. New social tables: challenges, challenge_hands, challenge_results,
--      activity_events, plus profile fields for public profiles.
--   3. Row Level Security on every user-scoped table.
--
-- Apply with:  supabase db push     (or paste into the SQL editor)
-- =====================================================================

-- ---------------------------------------------------------------------
-- Profiles (replaces StackSchool `users`)
--
-- Supabase convention: never write to auth.users. Mirror it into public.profiles
-- and hang all foreign keys off that.
-- ---------------------------------------------------------------------
create table public.profiles (
  id                uuid primary key references auth.users(id) on delete cascade,
  username          text unique not null,
  display_name      text,
  avatar_url        text,
  bio               text,
  is_public         boolean not null default true,   -- public profile / leaderboard opt-in
  xp                integer not null default 0,
  level             integer not null default 1,
  streak_count      integer not null default 0,
  last_active_date  date,
  created_at        timestamptz not null default now()
);
create index profiles_xp_idx on public.profiles (xp desc);
create index profiles_username_idx on public.profiles (lower(username));

comment on column public.profiles.level is
  'Derived: (xp / 100) + 1. Kept denormalised for cheap leaderboard reads, same as StackSchool.';

-- Auto-create a profile row whenever someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username, display_name)
  values (
    new.id,
    -- collision-safe default; the user can change it later
    coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1) || '_' || substr(new.id::text, 1, 4)),
    coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

