-- ---------------------------------------------------------------------
-- Helper: is the current user friends with X?
-- ---------------------------------------------------------------------
create or replace function public.is_friend(target uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.friends
    where user_id = auth.uid() and friend_user_id = target
  );
$$;

-- ---------------------------------------------------------------------
-- Row Level Security
--
-- Content tables are world-readable to signed-in users and writable only by
-- the service role (seeding/admin). Everything user-scoped is owner-only,
-- with friend visibility where the product needs it.
-- ---------------------------------------------------------------------
alter table public.profiles              enable row level security;
alter table public.modules               enable row level security;
alter table public.lessons               enable row level security;
alter table public.scenarios             enable row level security;
alter table public.table_scenarios       enable row level security;
alter table public.attempts              enable row level security;
alter table public.progress              enable row level security;
alter table public.skill_stats           enable row level security;
alter table public.user_daily_activity   enable row level security;
alter table public.daily_content         enable row level security;
alter table public.user_daily_completions enable row level security;
alter table public.friend_requests       enable row level security;
alter table public.friends               enable row level security;
alter table public.challenges            enable row level security;
alter table public.challenge_hands       enable row level security;
alter table public.challenge_results     enable row level security;
alter table public.activity_events        enable row level security;

-- Content: readable by any authenticated user.
create policy "content readable" on public.modules         for select to authenticated using (true);
create policy "content readable" on public.lessons         for select to authenticated using (true);
create policy "content readable" on public.scenarios       for select to authenticated using (true);
create policy "content readable" on public.table_scenarios for select to authenticated using (true);
create policy "content readable" on public.daily_content   for select to authenticated using (true);

-- Profiles: you can always see your own; others only if public or a friend.
create policy "read own profile"    on public.profiles for select to authenticated
  using (id = auth.uid() or is_public or public.is_friend(id));
create policy "update own profile"  on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

-- Owner-only tables.
create policy "own attempts"    on public.attempts    for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "own progress"    on public.progress    for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "own daily"       on public.user_daily_completions for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Stats and activity: yours, plus friends' (needed for the feed and leaderboards).
create policy "own or friend skill stats" on public.skill_stats for select to authenticated
  using (user_id = auth.uid() or public.is_friend(user_id));
create policy "write own skill stats" on public.skill_stats for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "own or friend activity" on public.user_daily_activity for select to authenticated
  using (user_id = auth.uid() or public.is_friend(user_id));
create policy "write own activity" on public.user_daily_activity for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "feed visible" on public.activity_events for select to authenticated
  using (user_id = auth.uid() or public.is_friend(user_id));
create policy "write own events" on public.activity_events for insert to authenticated
  with check (user_id = auth.uid());

-- Friends: see requests addressed to or from you.
create policy "see own requests" on public.friend_requests for select to authenticated
  using (from_user_id = auth.uid() or to_user_id = auth.uid());
create policy "send requests" on public.friend_requests for insert to authenticated
  with check (from_user_id = auth.uid());
create policy "respond to requests" on public.friend_requests for update to authenticated
  using (to_user_id = auth.uid());

create policy "see own friends" on public.friends for select to authenticated
  using (user_id = auth.uid() or friend_user_id = auth.uid());

-- Challenges: visible to both participants.
create policy "see own challenges" on public.challenges for select to authenticated
  using (creator_id = auth.uid() or opponent_id = auth.uid() or opponent_id is null);
create policy "create challenges" on public.challenges for insert to authenticated
  with check (creator_id = auth.uid());

-- Challenge hands are only readable by participants.
create policy "see challenge hands" on public.challenge_hands for select to authenticated
  using (exists (
    select 1 from public.challenges c
    where c.id = challenge_id and (c.creator_id = auth.uid() or c.opponent_id = auth.uid())
  ));

create policy "see challenge results" on public.challenge_results for select to authenticated
  using (exists (
    select 1 from public.challenges c
    where c.id = challenge_id and (c.creator_id = auth.uid() or c.opponent_id = auth.uid())
  ));
create policy "write own results" on public.challenge_results for insert to authenticated
  with check (user_id = auth.uid());

-- ---------------------------------------------------------------------
-- Leaderboard view — respects is_public, safe to select from the client.
-- ---------------------------------------------------------------------
create view public.leaderboard
with (security_invoker = true)
as
  select id, username, display_name, avatar_url, xp, level, streak_count
  from public.profiles
  where is_public
  order by xp desc;
